"""Puertos abstractos."""
from abc import ABC, abstractmethod
from typing import Optional

from src.domain.entities import Entrada


class EntradaRepository(ABC):
    @abstractmethod
    def find_by_id(self, entrada_id: int) -> Optional[Entrada]: ...
    @abstractmethod
    def find_by_codigo(self, codigo: str) -> Optional[Entrada]: ...
    @abstractmethod
    def find_by_compra_id(self, compra_id: int) -> list[Entrada]: ...
    @abstractmethod
    def list_all(self, compra_id: Optional[int] = None, usuario_id: Optional[int] = None) -> list[Entrada]: ...
    @abstractmethod
    def generar(self, compra_id: int) -> list[Entrada]: ...
    @abstractmethod
    def validar(self, codigo: str, evento_id: int) -> Optional[Entrada]: ...
    @abstractmethod
    def anular_por_compra(self, compra_id: int) -> None: ...
