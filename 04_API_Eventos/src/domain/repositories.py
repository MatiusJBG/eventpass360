"""Puertos abstractos (ABC)."""
from abc import ABC, abstractmethod
from decimal import Decimal
from typing import Optional

from src.domain.entities import Categoria, Evento, TipoEntrada


class CategoriaRepository(ABC):
    @abstractmethod
    def list(self) -> list[Categoria]: ...
    @abstractmethod
    def find_by_id(self, categoria_id: int) -> Optional[Categoria]: ...
    @abstractmethod
    def find_by_nombre(self, nombre: str) -> Optional[Categoria]: ...
    @abstractmethod
    def create(self, nombre: str, descripcion: str) -> Categoria: ...
    @abstractmethod
    def update(
        self, categoria_id: int, nombre=None, descripcion=None, estado=None, expected_version: Optional[int] = None
    ) -> Categoria: ...
    @abstractmethod
    def count_eventos(self, categoria_id: int) -> int: ...
    @abstractmethod
    def delete(self, categoria_id: int) -> None: ...
    @abstractmethod
    def deactivate(self, categoria_id: int) -> None: ...


class EventoRepository(ABC):
    @abstractmethod
    def list(self, q=None, categoria_id=None, incluir_inactivos: bool = False) -> list[Evento]: ...
    @abstractmethod
    def find_by_id(self, evento_id: int) -> Optional[Evento]: ...
    @abstractmethod
    def create(self, categoria_id: int, nombre: str, descripcion: str, lugar: str, fecha, imagen_url: str) -> Evento: ...
    @abstractmethod
    def update(self, evento_id: int, expected_version: Optional[int] = None, **fields) -> Evento: ...
    @abstractmethod
    def delete(self, evento_id: int) -> None: ...
    @abstractmethod
    def deactivate(self, evento_id: int) -> None: ...


class TipoEntradaRepository(ABC):
    @abstractmethod
    def list(self, evento_id: Optional[int] = None) -> list[TipoEntrada]: ...
    @abstractmethod
    def find_by_id(self, tipo_id: int) -> Optional[TipoEntrada]: ...
    @abstractmethod
    def find_by_evento_tipo(self, evento_id: int, tipo: str) -> Optional[TipoEntrada]: ...
    @abstractmethod
    def create(self, evento_id: int, tipo: str, precio: Decimal, stock: int) -> TipoEntrada: ...
    @abstractmethod
    def update(self, tipo_id: int, expected_version: Optional[int] = None, **fields) -> TipoEntrada: ...
    @abstractmethod
    def delete(self, tipo_id: int) -> None: ...
    @abstractmethod
    def deactivate(self, tipo_id: int) -> None: ...
    @abstractmethod
    def count_detalles(self, tipo_id: int) -> int: ...


class StockRepository(ABC):
    @abstractmethod
    def cotizar(self, items: list[dict]) -> dict: ...
    @abstractmethod
    def descontar(self, items: list[dict]) -> None: ...
    @abstractmethod
    def restaurar(self, items: list[dict]) -> None: ...
